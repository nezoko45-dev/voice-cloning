const DEFAULT_MODEL = "openai/gpt-4o-mini";
const DEFAULT_PROMPT = "You are a natural, friendly voice assistant. Be concise when speaking, follow my instructions, ask clarifying questions when needed, and never pretend to have performed actions you have not performed.";
const DEFAULT_TTS_ENDPOINT = "http://127.0.0.1:8080/v1/tts";
let creatingOffscreen = null;
let requestBusy = false;

async function ensureOffscreen() {
  const contexts = await chrome.runtime.getContexts({ contextTypes: ["OFFSCREEN_DOCUMENT"], documentUrls: [chrome.runtime.getURL("offscreen.html")] });
  if (contexts.length) return;
  if (creatingOffscreen) return creatingOffscreen;
  creatingOffscreen = chrome.offscreen.createDocument({
    url: "offscreen.html",
    reasons: ["USER_MEDIA"],
    justification: "Keep explicitly started microphone recognition active and play audio generated by the user's local speech server while the popup is closed."
  });
  try { await creatingOffscreen; } finally { creatingOffscreen = null; }
}
async function broadcast(message) {
  try { await chrome.runtime.sendMessage(message); } catch (_) {}
}
async function setListening(value) {
  await chrome.storage.local.set({ backgroundListening: value });
  await broadcast({ type: "VOICE_STATUS", listening: value, message: value ? "Background listening is on. You can close this popup." : "Background listening is off." });
}

// A tiny MessagePack encoder for the string-only Fish Speech /v1/tts request.
function msgpackString(value) {
  const bytes = new TextEncoder().encode(value);
  let head;
  if (bytes.length < 32) head = [0xa0 | bytes.length];
  else if (bytes.length < 256) head = [0xd9, bytes.length];
  else if (bytes.length < 65536) head = [0xda, (bytes.length >> 8) & 255, bytes.length & 255];
  else throw new Error("TTS text field is too long for this local request.");
  return new Uint8Array([...head, ...bytes]);
}
function encodeFishRequest(values) {
  const entries = Object.entries(values);
  const header = entries.length < 16 ? [0x80 | entries.length] : [0xde, (entries.length >> 8) & 255, entries.length & 255];
  const chunks = [new Uint8Array(header)];
  for (const [key, value] of entries) chunks.push(msgpackString(key), msgpackString(value));
  const size = chunks.reduce((sum, part) => sum + part.length, 0);
  const out = new Uint8Array(size);
  let offset = 0;
  for (const part of chunks) { out.set(part, offset); offset += part.length; }
  return out;
}
async function generateLocalSpeech(text) {
  const settings = await chrome.storage.local.get({
    ttsEndpoint: DEFAULT_TTS_ENDPOINT, ttsReferenceId: "", ttsApiKey: ""
  });
  const endpoint = String(settings.ttsEndpoint || DEFAULT_TTS_ENDPOINT).trim();
  if (!/^https?:\/\/(127\.0\.0\.1|localhost)(:\d+)?\//i.test(endpoint)) {
    throw new Error("For privacy, the TTS endpoint must use localhost or 127.0.0.1.");
  }
  const payload = { text: String(text).slice(0, 12000), format: "wav" };
  if (settings.ttsReferenceId.trim()) payload.reference_id = settings.ttsReferenceId.trim();
  const headers = { "Content-Type": "application/msgpack", "Accept": "audio/wav, audio/*, application/octet-stream" };
  if (settings.ttsApiKey.trim()) headers.Authorization = "Bearer " + settings.ttsApiKey.trim();
  const response = await fetch(endpoint, { method: "POST", headers, body: encodeFishRequest(payload) });
  if (!response.ok) {
    const detail = await response.text().catch(() => "");
    throw new Error("Local TTS server returned HTTP " + response.status + (detail ? ": " + detail.slice(0, 240) : "") + ". Check the endpoint and server logs.");
  }
  const type = response.headers.get("content-type") || "";
  if (type.includes("json") || type.includes("text/")) {
    const detail = await response.text().catch(() => "");
    throw new Error("Expected audio from the local TTS endpoint; got " + type + (detail ? ": " + detail.slice(0, 240) : ""));
  }
  const audio = await response.arrayBuffer();
  if (!audio.byteLength) throw new Error("The local TTS server returned an empty audio file.");
  await ensureOffscreen();
  const bytes = new Uint8Array(audio);
  let binary = "";
  for (let i = 0; i < bytes.length; i += 0x8000) binary += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
  await chrome.runtime.sendMessage({ target: "offscreen", type: "PLAY_AUDIO", audioBase64: btoa(binary), mimeType: type.includes("mpeg") ? "audio/mpeg" : (type.split(";")[0] || "audio/wav") });
  await broadcast({ type: "TTS_STATUS", message: "Generated and playing speech from your local TTS server." });
}
async function speakText(text) {
  const clean = String(text || "").trim();
  if (!clean) return;
  try {
    await generateLocalSpeech(clean);
  } catch (error) {
    await broadcast({ type: "TTS_STATUS", error: true, message: "Local speech error: " + (error.message || "Unknown error") });
    throw error;
  }
}
async function handleTranscript(rawText) {
  const text = String(rawText || "").trim();
  if (!text || requestBusy) return;
  requestBusy = true;
  await broadcast({ type: "VOICE_TRANSCRIPT", text });
  try {
    const settings = await chrome.storage.local.get({ apiKey: "", model: DEFAULT_MODEL, systemPrompt: DEFAULT_PROMPT, backgroundConversation: [] });
    if (!settings.apiKey) throw new Error("Add your OpenRouter API key in extension settings.");
    const history = Array.isArray(settings.backgroundConversation) ? settings.backgroundConversation.slice(-20) : [];
    history.push({ role: "user", content: text });
    const response = await fetch("https://openrouter.ai/api/v1/chat/completions", {
      method: "POST",
      headers: { "Authorization": "Bearer " + settings.apiKey, "Content-Type": "application/json", "X-OpenRouter-Title": "VoiceAgent Pocket" },
      body: JSON.stringify({ model: settings.model || DEFAULT_MODEL, messages: [{ role: "system", content: settings.systemPrompt || DEFAULT_PROMPT }, ...history], temperature: 0.7 })
    });
    const data = await response.json().catch(() => ({}));
    if (!response.ok) throw new Error(data?.error?.message || data?.message || ("HTTP " + response.status));
    const reply = data?.choices?.[0]?.message?.content;
    if (typeof reply !== "string" || !reply.trim()) throw new Error("The model returned an empty reply.");
    history.push({ role: "assistant", content: reply.trim() });
    await chrome.storage.local.set({ backgroundConversation: history.slice(-20) });
    await broadcast({ type: "VOICE_REPLY", text: reply.trim() });
    await speakText(reply.trim());
    await broadcast({ type: "VOICE_STATUS", listening: true, message: "Reply spoken using the local speech server. Background listening is continuing." });
  } catch (error) {
    await broadcast({ type: "VOICE_STATUS", listening: true, error: true, message: "Assistant/speech error: " + (error.message || "Unknown error") });
  } finally { requestBusy = false; }
}
chrome.runtime.onMessage.addListener((message, sender, sendResponse) => {
  if (message?.type === "VOICE_START") {
    (async () => { try { await ensureOffscreen(); await chrome.runtime.sendMessage({ target: "offscreen", type: "START_LISTENING" }); await setListening(true); sendResponse({ ok: true }); }
      catch (error) { sendResponse({ ok: false, error: error.message || String(error) }); } })();
    return true;
  }
  if (message?.type === "VOICE_STOP") {
    (async () => { try {
      const contexts = await chrome.runtime.getContexts({ contextTypes: ["OFFSCREEN_DOCUMENT"], documentUrls: [chrome.runtime.getURL("offscreen.html")] });
      if (contexts.length) await chrome.runtime.sendMessage({ target: "offscreen", type: "STOP_LISTENING" });
      await setListening(false); sendResponse({ ok: true });
    } catch (error) { sendResponse({ ok: false, error: error.message || String(error) }); } })();
    return true;
  }
  if (message?.type === "TTS_SPEAK") {
    speakText(message.text).then(() => sendResponse({ ok: true })).catch(error => sendResponse({ ok: false, error: error.message || String(error) }));
    return true;
  }
  if (message?.type === "VOICE_TRANSCRIPT_FINAL") { handleTranscript(message.text); return false; }
  if (message?.type === "OFFSCREEN_STATUS") {
    if (message.listening === false) chrome.storage.local.set({ backgroundListening: false });
    broadcast({ type: "VOICE_STATUS", listening: message.listening === true, message: message.message || "", error: message.error === true });
  }
});
chrome.runtime.onStartup.addListener(async () => {
  const state = await chrome.storage.local.get({ backgroundListening: false });
  if (state.backgroundListening) { try { await ensureOffscreen(); await chrome.runtime.sendMessage({ target: "offscreen", type: "START_LISTENING" }); } catch (_) {} }
});
chrome.runtime.onInstalled.addListener(() => { chrome.storage.local.get({ backgroundConversation: [] }).then(() => {}); });
